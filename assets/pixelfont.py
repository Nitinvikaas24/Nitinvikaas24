CHAR_W, CHAR_H = 5, 7


def text_to_rects(text, x0, y0, px, gap=1, char_gap=1):
    """Yield (x, y) grid cell positions (in px units, not yet scaled) that
    are 'on' for each character of text, left to right."""
    cells = []
    cx = x0
    for ch in text.upper():
        pattern = FONT_5x7.get(ch)
        if pattern is None:
            cx += CHAR_W + char_gap
            continue
        for row, bits in enumerate(pattern):
            for col, bit in enumerate(bits):
                if bit == "1":
                    cells.append((cx + col, y0 + row))
        cx += CHAR_W + char_gap
    return cells, cx  # cx = ending x (next cursor position)


def pixel_text_svg(text, x, y, scale, fill, id_prefix="pt", gap=0):
    """Return an SVG <g> string rendering text as pixel rects.
    x, y = top-left origin in final SVG units. scale = px unit size."""
    cells, end_cx = text_to_rects(text, 0, 0, scale)
    out = [f'<g id="{id_prefix}">']
    for (cx, cy) in cells:
        rx = x + cx * scale
        ry = y + cy * scale
        out.append(f'<rect x="{rx}" y="{ry}" width="{scale-gap}" height="{scale-gap}" fill="{fill}"/>')
    out.append("</g>")
    width = end_cx * scale
    height = CHAR_H * scale
    return "\n".join(out), width, height


def measure_pixel_text(text, scale):
    cells, end_cx = text_to_rects(text, 0, 0, scale)
    return end_cx * scale, CHAR_H * scale
